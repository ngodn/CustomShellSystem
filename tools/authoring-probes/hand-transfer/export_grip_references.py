"""Export the audited prop-to-hand reference for each outfit and shoulder weapon."""
import argparse
import json
import math
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('references', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
variants = {'peony':'peony', 'black-pearl':'black_pearl', 'unholy-eve':'unholy_eve',
            'unholy-genessa':'unholy_genessa', 'commander-white':'commander'}
weapons = {'ClockworkScythe':'scythe', 'HadernsSword':'hadern', 'BlackNeedle':'needle',
           'HeavyHammer':'hammer', 'BattleAxe':'battle_axe'}
references = json.loads(args.references.read_text())
identities = {(r['family'],r['weapon']) for r in references}
if len(references) != 25 or identities != {(v,w) for v in variants for w in weapons}:
    raise ValueError('Expected all five variants and five shoulder weapons exactly once')
lines = ['#pragma once', '#include "hand_support.hpp"', '',
         '// Generated by tools/authoring-probes/hand-transfer/export_grip_references.py.',
         'namespace css::hand_support {',
         'struct Grip {Variant variant;Weapon weapon;Quat rotation;std::array<double,3> translation;};',
         'inline constexpr Grip grips[] = {']
for ref in references:
    q = [ref['transform']['Rotation'][k] for k in 'XYZW']
    p = [ref['transform']['Translation'][k] for k in 'XYZ']
    norm = math.sqrt(sum(v*v for v in q))
    if not all(math.isfinite(v) for v in q+p) or abs(norm-1) > 1e-5:
        raise ValueError('Invalid measured grip transform')
    lines.append('    {Variant::'+variants[ref['family']]+',Weapon::'+weapons[ref['weapon']]+
                 ',Quat{'+','.join(format(v/norm,'.17g') for v in q)+'},{'+
                 ','.join(format(v,'.17g') for v in p)+'}},')
lines += ['};', 'inline const Grip* grip(Variant variant,Weapon weapon) {',
          '    for(const auto& g:grips) if(g.variant==variant && g.weapon==weapon) return &g;',
          '    return nullptr;', '}', '}', '']
args.output.write_text('\n'.join(lines))
