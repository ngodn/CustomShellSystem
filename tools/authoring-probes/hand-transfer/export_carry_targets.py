"""Export measured relaxed support targets in the saved rig's right-finger order."""
import argparse
import json
import math
from pathlib import Path

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('profiles',type=Path)
parser.add_argument('output',type=Path)
args=parser.parse_args()
families={'peony':'eve','unholy-eve':'unholy','commander-white':'commander'}
weapons={'ClockworkScythe':'scythe','HadernsSword':'hadern','BlackNeedle':'needle','HeavyHammer':'hammer','BattleAxe':'battle_axe'}
bones=[f'{finger}_{part}_r' for finger in ['pinky','ring','middle','index'] for part in ['metacarpal','01','02','03']]+['thumb_01_r','thumb_02_r','thumb_03_r']
profiles=json.loads(args.profiles.read_text())['profiles']
identities={(p['family'],p['weapon']) for p in profiles}
if len(profiles)!=15 or identities!={(f,w) for f in families for w in weapons}:raise ValueError('Expected every audited family and shoulder weapon exactly once')
lines=['#pragma once','#include "hand_support.hpp"','',
 '// Generated by tools/authoring-probes/hand-transfer/export_carry_targets.py.',
 '// Measurement scope and remaining checks: docs/development/shoulder-weapon-hold.md.',
 'namespace css::hand_support {',
 'struct Profile {Family family;Weapon weapon;Targets standing;};',
 'inline constexpr Profile profiles[] = {']
for profile in profiles:
 lines.append('    {Family::'+families[profile['family']]+',Weapon::'+weapons[profile['weapon']]+',')
 for phase in ['standing']:
  rotations=profile['phases'][phase]['rotations']
  if set(rotations)!=set(bones):raise ValueError('Unexpected carry bone set')
  lines.append('     Targets{{')
  for bone in bones:
   q=[float(rotations[bone][k]) for k in 'XYZW'];norm=math.sqrt(sum(v*v for v in q))
   if not math.isfinite(norm) or abs(norm-1)>1e-5:raise ValueError('Invalid measured quaternion: '+bone)
   lines.append('         Quat{'+','.join(format(v/norm,'.17g') for v in q)+'},')
  lines.append('     }}},')
lines+=['};','inline const Profile* profile(Family family,Weapon weapon) {',
        '    for(const auto& p:profiles) if(p.family==family && p.weapon==weapon) return &p;',
        '    return nullptr;','}','}','']
args.output.write_text('\n'.join(lines))
