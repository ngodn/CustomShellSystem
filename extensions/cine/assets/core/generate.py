"""Generate typed C++ row readers from the reviewed core schema (no defaults in generated code)."""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

def generate(schema):
    declarations = ['#pragma once', '// Generated by assets/core/generate.py. Edit schema.json, then regenerate.', '#include <array>', '#include <string>', '#include <vector>', '#include <nlohmann/json.hpp>', 'namespace cine {']
    readers = ['// Generated by assets/core/generate.py.']
    def emit(spec, name):
        kind = spec['type']
        if kind == 'number': return 'double'
        if kind == 'integer': return 'int'
        if kind == 'string': return 'std::string'
        if kind == 'boolean': return 'bool'
        if kind == 'array':
            item = emit(spec['items'], name + 'Item')
            if spec['min'] == spec['max']: return f'std::array<{item}, {spec["min"]}>'
            return f'std::vector<{item}>'
        fields = [(key, emit(child, name + ''.join(x.title() for x in key.split('_')))) for key, child in spec['fields'].items()]
        declarations.append('struct ' + name + ' {\n' + ''.join(f'    {t} {key}{{}};\n' for key,t in fields) + '};')
        readers.append(f'void from_json(const nlohmann::json& j, {name}& out) {{\n' + ''.join(f'    j.at("{key}").get_to(out.{key});\n' for key,_ in fields) + '}')
        return name
    fields=[]
    for row,spec in schema.items():
        member=row.split('.')[1]
        fields.append((row,member,emit(spec,'Core'+member.title())))
    declarations.append('struct CoreContent {\n'+''.join(f'    {t} {m}{{}};\n' for _,m,t in fields)+'};')
    declarations.append('} // namespace cine\n')
    readers.append('CoreContent decode_content(const nlohmann::json& rows) {\n    CoreContent out;\n'+''.join(f'    rows.at("{r}").get_to(out.{m});\n' for r,m,_ in fields)+'    return out;\n}\n')
    return {'core_types.hpp':'\n'.join(declarations),'core_decode.inc':'\n'.join(readers)}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for name,text in generate(json.loads((HERE/'schema.json').read_text())).items():
        path=ROOT/'src'/name
        if args.check:
            if not path.exists() or path.read_text()!=text: raise SystemExit(f'{path} needs regeneration')
        else: path.write_text(text)

if __name__=='__main__': main()
